// Writes src/shared/build-info.ts with the current git short hash so the
// running app can report the exact commit it was built from. Runs as a
// build prestep. Gracefully handles being outside a git work tree.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execSync } from 'node:child_process';

const __filename = fileURLToPath(import.meta.url);
const ROOT = path.resolve(path.dirname(__filename), '..');
const OUT = path.join(ROOT, 'src', 'shared', 'build-info.ts');

function safeShortHash() {
  try {
    return execSync('git rev-parse --short HEAD', {
      cwd: ROOT,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    return 'unknown';
  }
}

const hash = safeShortHash();
const content = `// Auto-generated by scripts/inject-build-hash.mjs at build time.
// Do not edit by hand; this file is gitignored.
export const BUILD_HASH = ${JSON.stringify(hash)} as const;
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, content);
console.log(`build-info: wrote BUILD_HASH=${hash}`);
